#!/usr/bin/env python3
"""Generate hardware/software/Tcl constants from the board-neutral SoC map."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out', type=Path, default=root / 'build/soc')
parser.add_argument('--get', choices=['reset_pc', 'ddr_base'])
args = parser.parse_args()
config = json.loads((root / 'hardware/soc/config/base.json').read_text())
values = {key: int(value, 0) for key, value in config.items() if key != 'name'}
if values['reset_pc'] != values['ddr_base']:
    parser.error('V1 JTAG boot requires reset_pc == ddr_base')
span = values['peripheral_span']
if span != 0x10000:
    parser.error('V1 register adapters decode 64 KiB windows')
bases = [values[f'{device}_base'] for device in ['sysctrl', 'gpio', 'uart']]
if len(set(bases)) != len(bases) or any(
        base % span or not 0x40000000 <= base < 0x80000000 for base in bases):
    parser.error('Peripheral bases must be distinct, 64 KiB aligned, within CPU MMIO')
if values['ddr_base'] != 0x80000000:
    parser.error('V1 DDR aperture is based at 0x80000000')
if args.get:
    print(hex(values[args.get]))
else:
    args.out.mkdir(parents=True, exist_ok=True)
    banner = 'Generated by scripts/soc-config.py; edit hardware/soc/config/base.json.'
    (args.out / 'soc-map.tcl').write_text(
        '# ' + banner + '\nset ::hision_map [dict create \\\n' +
        ''.join(f'    {key} 0x{value:x} \\\n' for key, value in values.items()) + ']\n')
    (args.out / 'hision_soc_map.h').write_text(
        '// ' + banner + '\n#ifndef HISION_SOC_MAP_H\n#define HISION_SOC_MAP_H\n' +
        ''.join(f'#define HISION_{key.upper()} 0x{value:x}UL\n' for key, value in values.items()) +
        '#endif\n')
    (args.out / 'hision_soc_map.vh').write_text(
        '// ' + banner + '\n' +
        ''.join(f'`define HISION_{key.upper()} 64\'h{value:016x}\n' for key, value in values.items()))
    print(f'SoC address definitions: {args.out}')
